    public static Ending Final(int[] s, string name)
    {
        int p = s[Stat.People], y = s[Stat.Youth], e = s[Stat.Economy], l = s[Stat.Link], m = s[Stat.Memory];
        if (p < 35 || y < 25)
            return new("ТИХОЕ УГАСАНИЕ",
                $"Последние жители села «{name}» доживают свой век. Технологии приходили, но не работали на село. " +
                "Через несколько лет на карте останется только название.", Pal.Coral, Mood.Overcast);
        if (p >= 55 && m >= 60 && y >= 48)
            return new("ВОЗРОЖДЕНИЕ",
                $"«{name}» в 2050 году — живое село, которое помнит своё прошлое. Здесь работают удалённо и на умных фермах, " +
                "дети учатся в своей школе, а в музее звучат голоса прадедов. Технологии стали инструментом, а не целью.",
                Pal.Green, Mood.Dawn);
        if (e >= 60 && l >= 60 && m < 56)
            return new("ТЕХНОПОЛИС БЕЗ КОРНЕЙ",
                $"Дроны, датчики, быстрый интернет — село «{name}» стало умным посёлком. Но старые дома снесены, а историю " +
                "никто не помнит. Технологии без памяти делают место удобным — но не родным.", Pal.Cyan, Mood.Night);
        if (m >= 70 && p < 50)
            return new("МУЗЕЙ ПОД ОТКРЫТЫМ НЕБОМ",
                $"Память о селе «{name}» бережно сохранена: оцифрованы фото, письма и голоса. Но жить здесь почти некому — " +
                "туристы приезжают посмотреть на прошлое, а настоящего у села нет.", Pal.Violet, Mood.Dusk);
        return new("ЖИВОЕ СЕЛО",
            $"Село «{name}» держится: не всё удалось, но оно живёт. Есть связь, есть работа, есть память. " +
            "Будущее ещё можно улучшить — и это зависит от людей.", Pal.Gold, Mood.Day);
    }

