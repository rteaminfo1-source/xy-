const wchar_t *hist_state_name(int year)
{
    for (unsigned i = 0; i < sizeof STATE_NAMES / sizeof STATE_NAMES[0]; i++)
        if (year <= STATE_NAMES[i].to) return STATE_NAMES[i].name;
    return STATE_NAMES[0].name;
}

void hist_area_years(const HistArea *a, int *from, int *to)
{
    /* одна земля может быть разбита на несколько записей подряд (менялась граница) — склеиваем их по имени и роли */
    int f = a->from, t = a->to, grow = 1;
    while (grow) {
        grow = 0;
        for (int i = 0; i < HIST_AREA_COUNT; i++) {
            const HistArea *b = &HIST_AREAS[i];
            if (b->role != a->role || wcscmp(b->name, a->name)) continue;
            if (b->to == f - 1) { f = b->from; grow = 1; }
            if (b->from == t + 1) { t = b->to; grow = 1; }
        }
    }
    *from = f;
    *to = t;
}

int hist_area_prio(int role)
{
    switch (role) {
    case HA_NEIGHBOR: return 0;
    case HA_STATE:    return 1;
    case HA_SUB:      return 2;
    case HA_PART:     return 3;
    default:          return 4;     /* HA_FOREIGN — поверх всех */
    }
}

int hist_areas_at(int year, int *idx, int max)
{
    int n = 0;
    for (int p = 0; p <= 4; p++)
        for (int i = 0; i < HIST_AREA_COUNT && n < max; i++)
            if (HIST_AREAS[i].from <= year && year <= HIST_AREAS[i].to && hist_area_prio(HIST_AREAS[i].role) == p) idx[n++] = i;
    return n;
}

static unsigned darker(unsigned c, float k)
{
    return (unsigned)((c >> 16 & 255) * k) << 16 | (unsigned)((c >> 8 & 255) * k) << 8 | (unsigned)((c & 255) * k);
}

int hist_t3_areas(int year, T3Area *out, int max)
{
    /* оттенок на плите Беларуси и темнота линии границы по роли: HA_STATE, HA_PART, HA_FOREIGN, HA_NEIGHBOR, HA_SUB */
    static const float SLAB[5] = { 0.20f, 0.26f, 0.16f, 0.14f, 0.18f }, LINE[5] = { 0.42f, 0.40f, 0.36f, 0.58f, 0.50f };
    if (max > T3_MAX_AREAS) max = T3_MAX_AREAS;
    int idx[T3_MAX_AREAS], nw = HIST_WATER_COUNT < max ? HIST_WATER_COUNT : max, n = nw + hist_areas_at(year, idx, max - nw);
    for (int k = 0; k < n; k++) {
        const HistArea *h = k < nw ? &HIST_WATER[k] : &HIST_AREAS[idx[k - nw]];
        T3Area *a = &out[k];
        memset(a, 0, sizeof *a);
        a->n = h->n;
        for (int i = 0; i < h->n; i++) {
            a->x[i] = (h->pts[i][0] - 28.0f) * 65.95f;
            a->y[i] = (h->pts[i][1] - 53.7f) * 111.32f;
        }
        a->color = h->color;
        a->line = darker(h->color, LINE[h->role]);
        a->slab = SLAB[h->role];
        a->stripes = h->role == HA_FOREIGN;
        a->plate = h->n > 0;
        a->prio = k < nw ? -1 : hist_area_prio(h->role);
        if (k < nw) a->slab = 0;
    }
    return n;
}

